function journey(
  partial: Omit<JourneyRecord, "isDemo" | "createdAt" | "updatedAt" | "selectedChannelIds" | "status"> & {
    status?: JourneyRecord["status"];
    selectedChannelIds?: string[];
    createdAt?: string;
  },
): JourneyRecord {
  const createdAt = partial.createdAt ?? "2026-09-12T12:00:00.000Z";
  return {
    status: partial.status ?? "active",
    selectedChannelIds: partial.selectedChannelIds ?? [],
    isDemo: true,
    createdAt,
    updatedAt: createdAt,
    ...partial,
  };
}

